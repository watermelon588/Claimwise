"""Turn live end-to-end results and the run trace into the validation plan and the performance report.

Usage (from the repository root):
    python e2e/report.py --results e2e/results/latest.json [more.json ...] --trace <TRACE_LOG file> --unit "52 passed"
        [--notes e2e/results/notes.json]

notes.json maps "<journey> <spec>" to an explanation shown next to that journey's failed checks.

Later result files replace whole journeys from earlier ones (used when a journey is rerun after a fix).
Writes docs/07-delivery/validation-plan.md and docs/07-delivery/performance-report.md.
"""

