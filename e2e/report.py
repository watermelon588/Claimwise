def merge(paths: list[Path]) -> dict:
    """Combine result files: each journey's checks and calls come from the last file that ran it."""
    specs, titles, by_journey, runs = {}, {}, {}, []
    for path in paths:
        data = json.loads(path.read_text(encoding="utf-8"))
        specs.update(data["specs"])
        titles.update(data["journeys"])
        runs.append(f"{data['run']} ({data['date']}, {data['seconds']} s, {', '.join(data['journeys'])})")
        for key in [*data["journeys"], "setup"]:
            checks = [c for c in data["checks"] if c["journey"] == key]
            calls = [c for c in data["calls"] if c["journey"] == key]
            if checks or calls or key not in by_journey:
                by_journey[key] = {"checks": checks, "calls": calls}
    return {"specs": specs, "titles": titles, "journeys": by_journey, "runs": runs}


def pct(values: list[float], p: float) -> float:
    """Nearest-rank percentile (p in 0..100) of a non-empty list."""
    ordered = sorted(values)
    return ordered[max(0, min(len(ordered) - 1, round(p / 100 * len(ordered) + 0.5) - 1))]


def stats_row(name: str, values: list[float]) -> str:
    """Markdown row: name, count, p50, p95, max (milliseconds)."""
    return f"| {name} | {len(values)} | {pct(values, 50):,.0f} | {pct(values, 95):,.0f} | {max(values):,.0f} |"


def validation(data: dict, unit: str, notes: dict) -> str:
    """The validation plan: every spec with its expected outcome and its live result."""
    checks = [c for j in data["journeys"].values() for c in j["checks"]]
    by_spec = defaultdict(list)
    for c in checks:
        by_spec[c["spec"]].append(c)
    passed = sum(c["ok"] for c in checks)
    lines = [
        "# Validation plan and results",
        "",
        "Status: run live on the synthetic-data prototype (session 037). Generated by `e2e/report.py` from the end-to-end "
        "harness `e2e/live_e2e.py`; do not edit by hand, rerun the harness and the report instead.",
        "",
        f"- Live end-to-end checks: **{passed} of {len(checks)} passed** across {len(data['titles'])} journeys "
        f"and {len(by_spec)} specs.",
        f"- Backend unit tests (`uv run pytest` in `backend/`): {unit}.",
        "- Runs merged: " + "; ".join(data["runs"]) + ".",
        "",
        "Each journey drives the real backend API like the browser does (uploads, chat, buttons, approval cards) against "
        "the connector gateway and the mock payer, hospital and bank, with the real models (Gemini, Groq fallback) and "
        "Postgres checkpoints. Mock operator calls play the insurer: raise a query, decide, pay, inject faults. Every "
        "document is synthetic. How to run it: [e2e/README.md](../../e2e/README.md).",
        "",
        "A spec with no live check would be labelled \"specification only\"; every spec below was exercised.",
        "",
        "## Coverage required by the brief",
        "",
        "| Required case | Specs |",
        "|---|---|",
        *[f"| {name} | {ids} |" for name, ids in COVERAGE],
        "",
        "## Specs",
        "",
        "| Id | Case | Expected outcome | Journeys | Result |",
        "|---|---|---|---|---|",
    ]
    for spec, (case, expected) in sorted(data["specs"].items()):
        got = by_spec.get(spec, [])
        journeys = ", ".join(sorted({c["journey"] for c in got})) or "none"
        if not got:
            result = "Specification only (not run)"
        elif all(c["ok"] for c in got):
            result = f"Passed ({len(got)} checks)"
        else:
            result = f"**Failed** {sum(not c['ok'] for c in got)} of {len(got)}"
        lines.append(f"| {spec} | {case} | {expected} | {journeys} | {result} |")
    lines += ["", "## Journeys", "", "| Journey | What it covers | Checks passed |", "|---|---|---|"]
    for key, title in data["titles"].items():
        got = data["journeys"].get(key, {}).get("checks", [])
        lines.append(f"| {key} | {title} | {sum(c['ok'] for c in got)} / {len(got)} |")
    failed = [c for c in checks if not c["ok"]]
    lines += ["", "## Failed checks", ""]
    lines += [f"- {c['journey']} {c['spec']} {c['check']}: `{c['detail'][:200]}`"
              + (f"\n  - Status: {notes[c['journey'] + ' ' + c['spec']]}" if c["journey"] + " " + c["spec"] in notes else "")
              for c in failed] or ["None."]
    lines += ["", "## Every check", "", "| Journey | Spec | Check | Result |", "|---|---|---|---|"]
    lines += [f"| {c['journey']} | {c['spec']} | {c['check']} | {'pass' if c['ok'] else 'FAIL'} |" for c in checks]
    return "\n".join(lines) + "\n"


def performance(data: dict, trace: list[dict]) -> str:
    """Latency per API route, per graph node, per model and per tool; token use; errors."""
    calls = [c for j in data["journeys"].values() for c in j["calls"]]
    api = defaultdict(list)
    for c in calls:
        if c["path"].startswith("/api/"):
            path = c["path"].split("?")[0]
            for prefix in ("/api/thread/", "/api/pack/"):
                if path.startswith(prefix):
                    path = prefix + "{id}" + ("/" + path.split("/", 4)[4] if path.count("/") > 3 else "")
            api[f"{c['method']} {path}"].append(c["ms"])
    lines = [
        "# Performance and observability report",
        "",
        "Status: measured on the live end-to-end run (session 037). Generated by `e2e/report.py`. Local machine, one user at a "
        "time, real model providers (free or entry tiers), Neon Postgres over the internet, mocks on localhost. Numbers "
        "show where time goes; they are not a capacity test.",
        "",
        "## How it is measured",
        "",
        "- **API latency:** the harness times every HTTP call it makes (what a user waits for).",
        "- **Inside a turn:** `backend/app/observability.py` adds a LangChain callback to every graph run. It writes one "
        "JSON line per graph node, model call and tool call (`TRACE_LOG`: name, ms, status, model, tokens). The same "
        "runs go to LangSmith (project `claimwise`, run name `claimwise:<route>`, thread id in metadata) when "
        "`LANGSMITH_API_KEY` is set.",
        "",
        "## Findings",
        "",
        *[f"- {f}" for f in FINDINGS],
        "",
        "## API latency (ms)",
        "",
        "| Route | Calls | p50 | p95 | Max |",
        "|---|---|---|---|---|",
        *[stats_row(k, v) for k, v in sorted(api.items(), key=lambda kv: -pct(kv[1], 50))],
    ]
    if trace:
        nodes, models, tools, errors = defaultdict(list), defaultdict(list), defaultdict(list), defaultdict(int)
        tokens = defaultdict(lambda: [0, 0])
        for t in trace:
            if t.get("status") == "error":
                errors[f"{t['kind']} {t['name']}"] += 1
            if t["kind"] == "node":
                nodes[t["name"]].append(t["ms"])
            elif t["kind"] == "llm":
                key = f"{t.get('provider') or '?'} {t.get('model') or '?'}"
                models[key].append(t["ms"])
                tokens[key][0] += t.get("input_tokens") or 0
                tokens[key][1] += t.get("output_tokens") or 0
            elif t["kind"] == "tool":
                tools[t["name"]].append(t["ms"])
        paused = sum(t.get("status") == "paused" for t in trace)
        lines += [
            "",
            f"## Graph nodes (ms, {sum(map(len, nodes.values()))} node runs; {paused} ended in an approval pause)",
            "",
            "| Node | Runs | p50 | p95 | Max |",
            "|---|---|---|---|---|",
            *[stats_row(k, v) for k, v in sorted(nodes.items(), key=lambda kv: -pct(kv[1], 95))],
            "",
            "## Model calls (ms)",
            "",
            "| Provider and model | Calls | p50 | p95 | Max |",
            "|---|---|---|---|---|",
            *[stats_row(k, v) for k, v in sorted(models.items())],
            "",
            "| Provider and model | Input tokens | Output tokens | Mean input per call |",
            "|---|---|---|---|",
            *[f"| {k} | {i:,} | {o:,} | {i / max(1, len(models[k])):,.0f} |" for k, (i, o) in sorted(tokens.items())],
            "",
            "## Tool calls (ms)",
            "",
            "| Tool | Calls | p50 | p95 | Max |",
            "|---|---|---|---|---|",
            *([stats_row(k, v) for k, v in sorted(tools.items())] or ["| none | 0 | | | |"]),
            "",
            "## Errors recorded inside runs",
            "",
            *([f"- {k}: {n}" for k, n in sorted(errors.items())] or ["None."]),
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Read the inputs and write both reports."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, nargs="+", required=True)
    ap.add_argument("--trace", type=Path)
    ap.add_argument("--unit", default="not recorded")
    ap.add_argument("--notes", type=Path)
    args = ap.parse_args()
    data = merge(args.results)
    trace = []
    if args.trace and args.trace.exists():
        trace = [json.loads(line) for line in args.trace.read_text(encoding="utf-8").splitlines() if line.strip()]
    OUT.mkdir(parents=True, exist_ok=True)
    notes = json.loads(args.notes.read_text(encoding="utf-8")) if args.notes else {}
    (OUT / "validation-plan.md").write_text(validation(data, args.unit, notes), encoding="utf-8")
    (OUT / "performance-report.md").write_text(performance(data, trace), encoding="utf-8")
    print("wrote", OUT / "validation-plan.md", "and", OUT / "performance-report.md")


if __name__ == "__main__":
    main()
